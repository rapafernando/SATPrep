"""Build static/css/tokens.css from replica/design/tokens.json and check contrast.

    python3 tools/build_tokens.py          # write tokens.css, check light and dark
    python3 tools/build_tokens.py --check  # only check; exit 1 on any AA failure

Standard library only. Uses replica/design/contrast.py (MIT, see CONTRAST-LICENSE.txt).
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "replica" / "design" / "tokens.json"
OUT = ROOT / "static" / "css" / "tokens.css"

spec = importlib.util.spec_from_file_location("contrast", ROOT / "replica" / "design" / "contrast.py")
contrast = importlib.util.module_from_spec(spec)
spec.loader.exec_module(contrast)


def color_vars(colors, indent="  "):
    return "\n".join(f"{indent}--color-{name}: {value};" for name, value in colors.items())


def build(tokens):
    t = tokens
    lines = ["/* GENERATED by tools/build_tokens.py from replica/design/tokens.json. Do not edit by hand. */", ":root {"]
    lines.append(color_vars(t["color"]))
    for name, f in t["font"].items():
        lines.append(f"  --font-{name}: {f};")
    for name, v in t["type"].items():
        lines.append(f"  --text-{name}: {v['size'] / 16:g}rem;")
        lines.append(f"  --leading-{name}: {v['line'] / 16:g}rem;")
    for i, v in enumerate(t["space"]):
        lines.append(f"  --space-{i}: {v / 16:g}rem;")
    for name, v in t["radius"].items():
        lines.append(f"  --radius-{name}: {v}px;")
    for name, v in t["size"].items():
        lines.append(f"  --size-{name}: {v}px;")
    for name, v in t["shadow"].items():
        lines.append(f"  --shadow-{name}: {v};")
    for name, v in t["motion"].items():
        lines.append(f"  --motion-{name}: {v};")
    lines.append("}")
    dark = color_vars(t["color-dark"], "    ")
    lines.append("@media (prefers-color-scheme: dark) {\n  :root {\n" + dark + "\n  }\n}")
    return "\n".join(lines) + "\n"


def check(tokens):
    failed = 0
    for mode, key in (("light", "color"), ("dark", "color-dark")):
        cols = contrast.colours({"color": tokens[key]})
        missing = set(tokens["color"]) ^ set(tokens["color-dark"])
        if missing:
            print(f"{mode}: roles differ between light and dark: {sorted(missing)}")
            failed += 1
        rows = contrast.check(cols, tokens["pairs"])
        print(f"{mode} mode")
        print(contrast.render(rows))
        failed += sum(1 for r in rows if "error" in r or not r["aa"])
    return failed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    if not a.check:
        OUT.write_text(build(tokens), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if check(tokens) else 0


if __name__ == "__main__":
    sys.exit(main())
